// Editing a check (design 29 D1). An edit names the version it was read at
// and only the fields it changes. It may change the name, interval, timeout,
// the tls warning window, the alert policy and how many failures in a row it
// waits for, whether the check runs, its sources and which of them are
// paused. It may not change the method or the
// target: that is a new check, so one series never mixes two of them, and
// the console creates the new check and pauses the old one. Generated
// checks refuse edits as they refuse deletes.

const (
	// monitorMinIntervalSec is the interval floor every save enforces.
	monitorMinIntervalSec = 10
	monitorMaxIntervalSec = 24 * 3600
	monitorMaxTimeoutSec  = 60
)

// errMonitorMethodChange is the answer to an edit that changes the method
// or the target.
func errMonitorMethodChange(field string) error {
	return fmt.Errorf("a check's %s cannot change: create a new check with the new %s and pause this one, so one path's history never mixes two of them", field, field)
}

// validMonitorAlert reports whether alert is a policy a save may store.
func validMonitorAlert(alert string) bool {
	return alert == "" || alert == model.MonitorAlertDown || alert == model.MonitorAlertOff
}

// monitorPages reports whether a monitor's failures page: an operator check
// whose alert policy is not off. Generated latency checks never page one
// pair at a time; a path's degradation is judged on its rollups instead.
func monitorPages(mon model.Monitor) bool {
	return mon.ManagedBy == "" && mon.Alert != model.MonitorAlertOff
}

// validMonitorTiming checks the interval and timeout a save stores.
func validMonitorTiming(intervalSec, timeoutSec int) error {
	if intervalSec < monitorMinIntervalSec || intervalSec > monitorMaxIntervalSec {
		return fmt.Errorf("interval_sec must be %d to %d", monitorMinIntervalSec, monitorMaxIntervalSec)
	}
	if timeoutSec < 1 || timeoutSec > monitorMaxTimeoutSec || timeoutSec >= intervalSec {
		return fmt.Errorf("timeout_sec must be 1 to %d and shorter than interval_sec", monitorMaxTimeoutSec)
	}
	return nil
}

// cleanNodeList trims, drops empties and repeats, and sorts.
func cleanNodeList(in []string) []string {
	set := map[string]bool{}
	for _, raw := range in {
		if nodeID := strings.TrimSpace(raw); nodeID != "" {
			set[nodeID] = true
		}
	}
	out := make([]string, 0, len(set))
	for nodeID := range set {
		out = append(out, nodeID)
	}
	sort.Strings(out)
	return out
}

// handleMonitorUpdate answers POST /api/monitors/update.
func (s *Server) handleMonitorUpdate(w http.ResponseWriter, r *http.Request, p principal) {
	if r.Method != http.MethodPost {
		writeError(w, http.StatusMethodNotAllowed, errors.New("method not allowed"))
		return
	}
	var req model.MonitorUpdate
	if !decodeClientJSON(w, r, &req) {
		return
	}
	s.monitorSaves.Lock()
	defer s.monitorSaves.Unlock()
	mon, ok := s.store.Monitor(strings.TrimSpace(req.ID))
	if !ok {
		writeError(w, http.StatusNotFound, apiError(model.APIErrorNotFound, "monitor not found"))
		return
	}
	if !monitorManageableByPrincipal(p, mon) {
		writeError(w, http.StatusForbidden, apiError(model.APIErrorCapabilityDenied, "forbidden"))
		return
	}
	if mon.ManagedBy != "" {
		writeError(w, http.StatusConflict, fmt.Errorf("monitor %s is generated by the %s probe configuration; change that configuration instead", mon.ID, mon.ManagedBy))
		return
	}
	next, changed, answered, err := s.applyMonitorUpdate(w, p, mon, req)
	if answered {
		return
	}
	if err != nil {
		writeError(w, http.StatusBadRequest, err)
		return
	}
	now := s.now()
	stored, err := s.store.UpdateMonitor(next, req.Version, now)
	switch {
	case errors.Is(err, store.ErrMonitorVersion):
		writeError(w, http.StatusConflict, err)
		return
	case errors.Is(err, store.ErrMonitorManaged):
		writeError(w, http.StatusConflict, err)
		return
	case errors.Is(err, store.ErrMonitorNotFound):
		writeError(w, http.StatusNotFound, apiError(model.APIErrorNotFound, "monitor not found"))
		return
	case err != nil:
		writeError(w, http.StatusInternalServerError, err)
		return
	}
	meta := map[string]string{
		"monitor_id": stored.ID,
		"type":       stored.Type,
		"version":    strconv.FormatInt(stored.Version, 10),
		"changed":    strings.Join(changed, ","),
	}
	if slices.Contains(changed, "node_ids") || slices.Contains(changed, "assign_all") {
		meta["node_ids"] = latencyIDList(stored.NodeIDs)
		meta["assign_all"] = strconv.FormatBool(stored.AssignAll)
	}
	if slices.Contains(changed, "paused_node_ids") {
		meta["paused_node_ids"] = latencyIDList(stored.PausedNodeIDs)
	}
	if slices.Contains(changed, "headers") {
		// Names and secrecy only: a value never reaches an audit record.
		meta["headers"] = monitorHeaderNames(stored.Headers)
	}
	s.recordPrincipalAudit(p, model.AuditEvent{
		ID:       id.New("audit"),
		At:       now.UTC(),
		Action:   "monitor.update",
		Scope:    "monitor:admin",
		Decision: "allow",
		Metadata: meta,
	})
	latest, err := s.store.LatestMonitorResults()
	if err != nil {
		writeError(w, http.StatusInternalServerError, err)
		return
	}
	view := s.monitorViews([]model.Monitor{stored}, now)[0]
	view.Latest = monitorLatestViews(p, stored, latest[stored.ID])
	writeJSON(w, http.StatusOK, view)
}

// applyMonitorUpdate is mon with req applied, and the names of the fields
// that changed. An error is a bad request. answered is true when a scope
// refusal was already written to w.
func (s *Server) applyMonitorUpdate(w http.ResponseWriter, p principal, mon model.Monitor, req model.MonitorUpdate) (next model.Monitor, changed []string, answered bool, err error) {
	next = mon
	next.NodeIDs = slices.Clone(mon.NodeIDs)
	next.PausedNodeIDs = slices.Clone(mon.PausedNodeIDs)
	next.Headers = slices.Clone(mon.Headers)
	note := func(field string, differs bool) {
		if differs {
			changed = append(changed, field)
		}
	}
	tls := mon.Type == model.MonitorTypeTLS
	if req.Type != nil && strings.TrimSpace(*req.Type) != mon.Type {
		return model.Monitor{}, nil, false, errMonitorMethodChange("method")
	}
	if req.TargetNode != nil && strings.TrimSpace(*req.TargetNode) != mon.TargetNode {
		return model.Monitor{}, nil, false, errMonitorMethodChange("target_node")
	}
	// A check that names a node has the target the control plane resolves,
	// which may have moved since the editor read it; target_node is what
	// cannot change.
	if req.Target != nil && mon.TargetNode == "" {
		target := strings.TrimSpace(*req.Target)
		if tls {
			if host, port, err := splitTLSTarget(target); err == nil {
				target = net.JoinHostPort(host, port)
			}
		}
		if target != mon.Target {
			return model.Monitor{}, nil, false, errMonitorMethodChange("target")
		}
	}
	if req.Name != nil {
		name := strings.TrimSpace(*req.Name)
		if name == "" {
			return model.Monitor{}, nil, false, errors.New("name cannot be empty")
		}
		note("name", name != mon.Name)
		next.Name = name
	}
	if req.IntervalSec != nil {
		note("interval_sec", *req.IntervalSec != mon.IntervalSec)
		next.IntervalSec = *req.IntervalSec
	}
	if req.TimeoutSec != nil {
		note("timeout_sec", *req.TimeoutSec != mon.TimeoutSec)
		next.TimeoutSec = *req.TimeoutSec
	}
	if req.Packets != nil {
		if mon.Type != model.MonitorTypeICMP {
			return model.Monitor{}, nil, false, errors.New("packets applies to icmp checks only")
		}
		if *req.Packets < 1 || *req.Packets > model.MonitorPacketsMax {
			return model.Monitor{}, nil, false, fmt.Errorf("packets must be 1 to %d", model.MonitorPacketsMax)
		}
		note("packets", *req.Packets != model.MonitorPackets(mon))
		next.Packets = *req.Packets
	}
	if req.IntervalSec != nil || req.TimeoutSec != nil || req.Packets != nil {
		if err := validMonitorTiming(next.IntervalSec, next.TimeoutSec); err != nil {
			return model.Monitor{}, nil, false, err
		}
		if err := validMonitorRun(next); err != nil {
			return model.Monitor{}, nil, false, err
		}
	}
	// An empty expect_status echoed by an editor on another kind changes
	// nothing.
	expectSent := req.ExpectStatus != nil && (mon.Type == model.MonitorTypeHTTP || strings.TrimSpace(*req.ExpectStatus) != "")
	if expectSent || len(req.Headers) > 0 {
		if mon.Type != model.MonitorTypeHTTP {
			return model.Monitor{}, nil, false, errors.New("expect_status and headers apply to http checks only")
		}
		if req.ExpectStatus != nil {
			next.ExpectStatus = *req.ExpectStatus
		}
		if len(req.Headers) > 0 {
			headers, err := applyMonitorHeaderEdits(mon.Headers, req.Headers)
			if err != nil {
				return model.Monitor{}, nil, false, err
			}
			next.Headers = headers
		}
		if err := normalizeHTTPMonitor(&next, false); err != nil {
			return model.Monitor{}, nil, false, err
		}
		note("expect_status", next.ExpectStatus != canonicalMonitorExpectStatus(mon.ExpectStatus))
		note("headers", !monitorHeadersEqual(next.Headers, mon.Headers))
	}
	if req.ThresholdDays != nil {
		if !tls {
			return model.Monitor{}, nil, false, errors.New("threshold_days applies to tls checks only")
		}
		if *req.ThresholdDays < 1 || *req.ThresholdDays > tlsMonitorMaxThresholdDays {
			return model.Monitor{}, nil, false, fmt.Errorf("threshold_days must be between 1 and %d", tlsMonitorMaxThresholdDays)
		}
		note("threshold_days", *req.ThresholdDays != mon.ThresholdDays)
		next.ThresholdDays = *req.ThresholdDays
	}
	if req.Alert != nil {
		alert := strings.TrimSpace(*req.Alert)
		if !validMonitorAlert(alert) {
			return model.Monitor{}, nil, false, fmt.Errorf("alert must be %q or %q", model.MonitorAlertDown, model.MonitorAlertOff)
		}
		if alert == "" {
			alert = model.MonitorAlertDown
		}
		note("alert", alert != mon.Alert)
		next.Alert = alert
	}
	if req.AlertAfter != nil {
		if *req.AlertAfter < 1 || *req.AlertAfter > model.MonitorAlertAfterMax {
			return model.Monitor{}, nil, false, fmt.Errorf("alert_after must be 1 to %d", model.MonitorAlertAfterMax)
		}
		note("alert_after", *req.AlertAfter != store.MonitorAlertAfter(mon))
		next.AlertAfter = *req.AlertAfter
	}
	if req.Enabled != nil {
		note("enabled", *req.Enabled != mon.Enabled)
		next.Enabled = *req.Enabled
	}
	if tls {
		if (req.AssignAll != nil && *req.AssignAll) || (req.NodeIDs != nil && len(*req.NodeIDs) > 0) || (req.PausedNodeIDs != nil && len(*req.PausedNodeIDs) > 0) {
			return model.Monitor{}, nil, false, errors.New("a tls check runs on the control plane: it has no sources to assign or pause")
		}
		return next, changed, false, nil
	}
	nodes := map[string]bool{}
	for _, n := range s.store.Nodes() {
		nodes[n.ID] = true
	}
	if req.AssignAll != nil {
		note("assign_all", *req.AssignAll != mon.AssignAll)
		next.AssignAll = *req.AssignAll
	}
	if req.NodeIDs != nil {
		list := cleanNodeList(*req.NodeIDs)
		for _, nodeID := range list {
			if !nodes[nodeID] && !slices.Contains(mon.NodeIDs, nodeID) {
				return model.Monitor{}, nil, false, fmt.Errorf("node_ids names %q, which is not a node", nodeID)
			}
		}
		note("node_ids", !slices.Equal(list, cleanNodeList(mon.NodeIDs)))
		next.NodeIDs = list
	}
	if next.AssignAll {
		next.NodeIDs = nil
	}
	if req.AssignAll != nil || req.NodeIDs != nil {
		switch {
		case next.AssignAll && principalHasNodeRestriction(p):
			writeError(w, http.StatusForbidden, apiError(model.APIErrorCapabilityDenied, "restricted token cannot assign monitor to all nodes"))
			return model.Monitor{}, nil, true, nil
		case next.AssignAll:
			if !rbac.Allows(p.Principal, "monitor:admin", "") {
				writeError(w, http.StatusForbidden, apiError(model.APIErrorCapabilityDenied, "forbidden"))
				return model.Monitor{}, nil, true, nil
			}
		case len(next.NodeIDs) == 0:
			return model.Monitor{}, nil, false, errors.New("set assign_all or provide node_ids")
		default:
			// Every source the edit names, kept or added, needs the
			// caller's admin scope, as creating the check did.
			if !s.requireAllNodeScopes(w, p, "monitor:admin", next.NodeIDs) {
				return model.Monitor{}, nil, true, nil
			}
		}
	}
	assigned := func(nodeID string) bool {
		if next.AssignAll {
			return nodes[nodeID]
		}
		return slices.Contains(next.NodeIDs, nodeID)
	}
	if req.PausedNodeIDs != nil {
		list := cleanNodeList(*req.PausedNodeIDs)
		for _, nodeID := range list {
			if !assigned(nodeID) {
				return model.Monitor{}, nil, false, fmt.Errorf("paused_node_ids names %q, which is not one of the check's sources", nodeID)
			}
			if !rbac.Allows(p.Principal, "monitor:admin", nodeID) {
				writeError(w, http.StatusForbidden, apiError(model.APIErrorCapabilityDenied, "forbidden"))
				return model.Monitor{}, nil, true, nil
			}
		}
		note("paused_node_ids", !slices.Equal(list, cleanNodeList(mon.PausedNodeIDs)))
		next.PausedNodeIDs = list
	} else {
		// A source taken off the check leaves its paused list too.
		kept := next.PausedNodeIDs[:0]
		for _, nodeID := range next.PausedNodeIDs {
			if assigned(nodeID) {
				kept = append(kept, nodeID)
			}
		}
		if len(kept) != len(mon.PausedNodeIDs) {
			changed = append(changed, "paused_node_ids")
		}
		next.PausedNodeIDs = kept
	}
	if len(next.PausedNodeIDs) == 0 {
		next.PausedNodeIDs = nil
	}
	loadChanged := slices.ContainsFunc(changed, func(field string) bool {
		switch field {
		case "interval_sec", "packets", "node_ids", "assign_all", "paused_node_ids", "enabled":
			return true
		}
		return false
	})
	if model.MonitorKindSendsPackets(next.Type) && next.Enabled && loadChanged {
		if err := s.monitorTargetsAt(s.now()).checkPacketBudget(s.store.Monitors(), next); err != nil {
			return model.Monitor{}, nil, false, err
		}
	}
	return next, changed, false, nil
}
